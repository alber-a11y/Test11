let dict = ru;
export let lang: 'ru' | 'en' = 'ru';

export function setLang(l: 'auto' | 'ru' | 'en') {
  const resolved = l === 'auto' ? (navigator.language || 'en').toLowerCase().startsWith('ru') || /^(uk|be|kk)/.test(navigator.language) ? 'ru' : 'en' : l;
  lang = resolved;
  dict = resolved === 'ru' ? ru : en;
  document.documentElement.lang = resolved;
}

export function t(key: string, params?: Record<string, string | number>): string {
  let s = dict[key] ?? en[key] ?? key;
  if (params) for (const k in params) s = s.replace(`{${k}}`, String(params[k]));
  return s;
}
